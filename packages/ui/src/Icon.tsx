type Groups = typeof ICON_GROUPS;

export type IconName = { [G in keyof Groups]: keyof Groups[G] }[keyof Groups];

const ICONS = Object.assign({}, ...Object.values(ICON_GROUPS)) as Record<IconName, LucideIcon>;

export const ICON_NAMES = Object.keys(ICONS) as IconName[];

/** Whether a string names one of the icons. */
export function isIconName(name: string): name is IconName {
  return Object.hasOwn(ICONS, name);
}

export interface IconProps {
  name: IconName;
  /** Width and height in px. Default 20, the size SideNav uses; Toolbar uses 16. */
  size?: number;
  className?: string;
  /** Accessible name; omit for a decorative icon beside a text label. */
  label?: string;
}

/** A stroke icon drawn in the current text color. */
export function Icon({ name, size = 20, className, label }: IconProps) {
  const Glyph = ICONS[name];
  return (
    <Glyph
      size={size}
      strokeWidth={1.75}
      className={className}
      aria-hidden={label ? undefined : true}
      aria-label={label}
      role={label ? 'img' : undefined}
      focusable="false"
    />
  );
}
