function weapon(id: string, input: Omit<WeaponDefinition, 'id' | 'category'>): WeaponDefinition {
  return { id, category: 'weapon', ...input };
}

function ammunition(
  id: string,
  input: Omit<AmmunitionDefinition, 'id' | 'category'>,
): AmmunitionDefinition {
  return { id, category: 'ammunition', ...input };
}

